/* ---------- копирование записей в другой день ---------- */
function openCopy(list) {
  const t = fkey(new Date());
  nSheet(`<h3>Копировать в день</h3>
    <div class="wq">${[['Вчера', -1], ['Сегодня', 0], ['Завтра', 1]].map(([x, d]) => `<button data-cp="${shiftDay(t, d)}">${x}</button>`).join('')}</div>
    <div class="opt"><input type="date" id="cpd" class="dateinp" value="${shiftDay(t, 0)}"></div>
    <button class="big" id="cpok">Копировать</button>`, () => {
    const go_ = key => {
      const l = dayLog(key), base = fdateObj(key).getTime() + 12 * 3600e3 + l.length;
      list.forEach((e, i) => l.push(Object.assign({}, e, { id: Date.now() + '' + i + Math.floor(Math.random() * 1000), ts: base + i })));
      saveLog(key, l); closeSheet(); toast('Скопировано', dayLabel(key) + ': ' + list.length + ' ' + (list.length === 1 ? 'запись' : 'записей'));
    };
    document.querySelectorAll('[data-cp]').forEach(b => b.onclick = () => go_(b.dataset.cp));
    $('#cpok').onclick = () => { const v = $('#cpd').value; if (v) go_(v); };
  });
}

