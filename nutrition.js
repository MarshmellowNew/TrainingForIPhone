function wzWheel(k) {
  const u = wz.u;
  if (k === 'u') return openSheet(`<div class="grab"></div><div class="whd"><h3>Единицы измерения</h3><button class="wx" id="wxc" aria-label="Закрыть">${I.close}</button></div>
    <div class="wlist in">${[['met', 'Метрические', 'кг · см · км · мл'], ['imp', 'Имперские', 'фнт · дюйм. · ми · жидк. унц.']].map(([v, t, d]) => `<button class="wopt ${u === v ? 'on' : ''}" data-uu="${v}"><div><b>${t}</b><small>${d}</small></div><span class="wrad"></span></button>`).join('')}</div>
    <button class="big" id="wok">Сохранить</button>`, () => {
    let cur = u; $('#wxc').onclick = closeSheet;
    document.querySelectorAll('[data-uu]').forEach(b => b.onclick = () => { cur = b.dataset.uu; document.querySelectorAll('[data-uu]').forEach(x => x.classList.toggle('on', x === b)); });
    $('#wok').onclick = () => { wz.u = cur; closeSheet(); wzDraw(); };
  });
  if (k === 'b') {
    const t = new Date(), y0 = t.getFullYear(), cur = wz.birth ? wz.birth.split('-').map(Number) : [y0 - 30, 1, 1], ys = range(y0 - 100, y0 - 10);
    return openWheel('Дата рождения', [{ items: range(1, 31).map(String), idx: cur[2] - 1, flex: .7 }, { items: MONTHS_G, idx: cur[1] - 1, flex: 1.3 }, { items: ys.map(String), idx: ys.indexOf(cur[0]) < 0 ? 70 : ys.indexOf(cur[0]), flex: 1 }], 'Далее', r => {
      const y = ys[r[2]], m = r[1] + 1, d = Math.min(r[0] + 1, new Date(y, m, 0).getDate());
      wz.birth = y + '-' + String(m).padStart(2, '0') + '-' + String(d).padStart(2, '0'); wzDraw();
    });
  }
  if (k === 'h') return heightWheel(wz.h, u, v => { wz.h = v; wzDraw(); });
  const key = k === 'g' ? 'gw' : 'w';
  weightWheel(k === 'g' ? 'Желаемый вес' : 'Вес', wz[key], u, v => { wz[key] = v; wzDraw(); });
}
function heightWheel(h, u, cb) {
  if (u === 'imp') { const t = Math.round(h / CM_IN), f = Math.floor(t / 12), i = t % 12; return openWheel('Рост', [{ items: range(3, 8).map(x => x + ' фт'), idx: Math.max(0, Math.min(5, f - 3)) }, { items: range(0, 11).map(x => x + ' дюйм.'), idx: i }], 'Далее', r => cb(r1((((r[0] + 3) * 12) + r[1]) * CM_IN))); }
  const cm = Math.floor(h), mm = h - cm >= .5 ? 1 : 0, cs = range(120, 230);
  openWheel('Рост', [{ items: cs.map(x => x + ' см'), idx: Math.max(0, Math.min(cs.length - 1, cm - 120)), flex: 1.6 }, { items: ['0 мм', '5 мм'], idx: mm }], 'Далее', r => cb(cs[r[0]] + r[1] * .5));
}
function weightWheel(ttl, v, u, cb) {
  if (u === 'imp') { const lb = v * LB, a = Math.floor(lb), b = Math.min(9, Math.round((lb - a) * 10)), ls = range(66, 550); return openWheel(ttl, [{ items: ls.map(x => x + ' фнт'), idx: Math.max(0, Math.min(ls.length - 1, a - 66)), flex: 1.6 }, { items: range(0, 9).map(x => ',' + x), idx: b }], 'Далее', r => cb(r1((ls[r[0]] + r[1] / 10) / LB))); }
  const kg = Math.floor(v), g = Math.min(9, Math.round((v - kg) * 10)), ks = range(30, 250);
  openWheel(ttl, [{ items: ks.map(x => x + ' кг'), idx: Math.max(0, Math.min(ks.length - 1, kg - 30)), flex: 1.6 }, { items: range(0, 9).map(x => x * 100 + ' г'), idx: g }], 'Далее', r => cb(ks[r[0]] + r[1] / 10));
}

